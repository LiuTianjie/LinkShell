"""Bundle the reviewed SVGs for Metro without an SVG transformer or network IO."""
import json
from pathlib import Path

source = Path(__file__).resolve().parent
manifest = json.loads((source / 'manifest.json').read_text())
assert manifest['version'] == 1 and len(manifest['glyphs']) == 16
entries = [dict(id=g['id'], **{mode: (source / g['files'][mode]).read_text().strip()
                             for mode in ('light', 'dark')}) for g in manifest['glyphs']]
target = source.parents[2] / 'apps/client/src/theme/subagent-glyphs.ts'
target.write_text('// Generated by docs/design/subagent-icons-2026-10-21/export-client.py.\n'
                  '// Version 1 order is frozen: adding glyphs must not remap existing agents.\n'
                  'export const subagentGlyphs = ' + json.dumps(entries, ensure_ascii=False, indent=2) + ' as const;\n')
