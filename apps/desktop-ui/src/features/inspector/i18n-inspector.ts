const INSPECTOR_DICTS: Record<Locale, Record<InspectorCopyKey, string>> = {
  zh: inspectorZh,
  en: inspectorEn,
  ja: inspectorJa,
};

function formatTemplate(
  template: string,
  params?: Record<string, string | number>,
): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_m, key: string) => {
    const val = params[key];
    return val === undefined ? `{${key}}` : String(val);
  });
}

export interface InspectorI18n {
  locale: Locale;
  t: TranslateFn;
  ti: (key: InspectorCopyKey, params?: Record<string, string | number>) => string;
  revealLabel: string;
  fileManagerName: string;
  resolvedPlatform: DesktopPlatform;
}

export function useConnectionTargetPlatform(
  connection?: Connection,
): string | undefined {
  return useSyncExternalStore(
    (onStoreChange) =>
      connection ? connection.store.subscribe(onStoreChange) : () => {},
    () =>
      connection?.store.getState().machine?.platform ??
      connection?.computer.machine.platform,
    () => connection?.computer.machine.platform,
  );
}

export function useInspectorI18n(targetPlatform?: string): InspectorI18n {
  const { locale, t } = useI18n();
  const activePlatform = useActiveDesktopPlatform();
  const resolvedPlatform = resolveTargetPlatform(targetPlatform, activePlatform);
  return useMemo<InspectorI18n>(() => {
    const dict = INSPECTOR_DICTS[locale] ?? inspectorZh;
    return {
      locale,
      t,
      ti: (key, params) => formatTemplate(dict[key] ?? inspectorZh[key], params),
      revealLabel: revealInFilesLabel(locale, resolvedPlatform),
      fileManagerName: fileManagerLabel(locale, resolvedPlatform),
      resolvedPlatform,
    };
  }, [locale, resolvedPlatform, t]);
}

/** For code outside React (the remote-port responder) that still speaks the user's language. */
export function inspectorText(
  key: InspectorCopyKey,
  params?: Record<string, string | number>,
): string {
  const dict = INSPECTOR_DICTS[getDesktopLocale()] ?? inspectorZh;
  return formatTemplate(dict[key] ?? inspectorZh[key], params);
}
