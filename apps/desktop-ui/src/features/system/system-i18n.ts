const SYSTEM_DICTS: Record<Locale, SystemDictionary> = {
  zh: systemZh,
  en: systemEn,
  ja: systemJa,
};

function interpolateSystem(
  template: string,
  params?: Record<string, string | number>,
): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_m, key: string) => {
    const val = params[key];
    return val === undefined ? `{${key}}` : String(val);
  });
}

export function translateSystem(
  locale: Locale,
  key: SystemI18nKey,
  params?: Record<string, string | number>,
): string {
  const dict = SYSTEM_DICTS[locale] ?? systemZh;
  return interpolateSystem(dict[key] ?? systemZh[key], params);
}

const PAGE_NAV_KEYS: Record<ManagePage, SystemI18nKey> = {
  overview: "nav.overview",
  devices: "nav.devices",
  password: "nav.password",
  usage: "nav.usage",
  log: "nav.log",
  updates: "nav.updates",
  settings: "nav.settings",
};

export function useSystemI18n() {
  const { locale, preference, setPreference, t: tCore } = useI18n();
  const activePlatform = useActiveDesktopPlatform();
  return useMemo(() => {
    const computer = thisComputerLabel(locale, activePlatform);
    const computerSpaced = thisComputerSpacedLabel(locale, activePlatform);
    const revealInFiles = revealInFilesLabel(locale, activePlatform);
    const ts = (key: SystemI18nKey, params?: Record<string, string | number>) =>
      translateSystem(locale, key, {
        computer,
        computerSpaced,
        ...params,
      });
    const pageTitle = (page: ManagePage) => ts(PAGE_NAV_KEYS[page]);
    /** A management-store message: text as given, a key in this page's language. */
    const tm = (message: ManagementMessage | undefined) =>
      !message ? "" : typeof message === "string" ? message : ts(message.key, message.params);
    return {
      tm,
      locale,
      preference,
      setPreference,
      tCore,
      ts,
      pageTitle,
      computer,
      computerSpaced,
      revealInFiles,
    };
  }, [activePlatform, locale, preference, setPreference, tCore]);
}
