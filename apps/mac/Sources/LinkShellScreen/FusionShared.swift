/// The remote app's menus as the stub mirrors them (AX menu item attributes → AppKit).
public enum FusionMenuModel {
  /// `AXMenuItemCmdModifiers`: 0 is ⌘ alone; bit 0 adds ⇧, bit 1 ⌥, bit 2 ⌃, bit 3 removes ⌘.
  public static func modifiers(_ ax: Int) -> NSEvent.ModifierFlags {
    var flags: NSEvent.ModifierFlags = []
    if ax & 8 == 0 { flags.insert(.command) }
    if ax & 1 != 0 { flags.insert(.shift) }
    if ax & 2 != 0 { flags.insert(.option) }
    if ax & 4 != 0 { flags.insert(.control) }
    return flags
  }

  /// AppKit wants lowercase for unshifted letters; an uppercase letter would imply ⇧.
  public static func keyEquivalent(_ key: String) -> String {
    key.count == 1 ? key.lowercased() : ""
  }

  /// Bar items the stub provides itself (its app menu is this Mac's; Apple's menu is the system's).
  /// Index 0 is the Apple menu and 1 the app menu in every AX menu bar.
  public static func mirrorsTopLevel(index: Int) -> Bool { index >= 2 }

  public static func pathKey(_ path: [Int]) -> String { path.map(String.init).joined(separator: ".") }
}
