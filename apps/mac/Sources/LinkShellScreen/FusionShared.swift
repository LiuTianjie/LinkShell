/// Ids recently closed, so a late frame cannot resurrect them. Bounded: oldest forgotten first.
public struct FusionTombstones {
  private var order: [UInt32] = []
  private var members: Set<UInt32> = []
  public let capacity: Int

  public init(capacity: Int) { self.capacity = max(1, capacity) }

  public mutating func insert(_ id: UInt32) {
    guard members.insert(id).inserted else { return }
    order.append(id)
    if order.count > capacity {
      let evicted = order.removeFirst()
      members.remove(evicted)
    }
  }

  public mutating func remove(_ id: UInt32) {
    guard members.remove(id) != nil else { return }
    order.removeAll { $0 == id }
  }

  public func contains(_ id: UInt32) -> Bool { members.contains(id) }
  public var count: Int { members.count }
}

/// Chords a fused window keeps on this Mac. Everything else goes to the remote app, as typed.
/// Hiding and minimizing are window management, which is this Mac's job: sent to the remote,
/// ⌘H would hide the app there and its windows here would simply vanish.
public enum FusionLocalShortcut: Equatable {
  case hide, hideOthers, minimize, cycleWindows, cycleWindowsBackward
}

public enum FusionShortcuts {
  static let keyH: UInt16 = 4
  static let keyM: UInt16 = 46
  static let keyGrave: UInt16 = 50

  public static func local(keyCode: UInt16, modifiers: NSEvent.ModifierFlags) -> FusionLocalShortcut? {
    let flags = modifiers.intersection([.command, .option, .control, .shift])
    switch (keyCode, flags) {
    case (keyH, [.command]): return .hide
    case (keyH, [.command, .option]): return .hideOthers
    case (keyM, [.command]): return .minimize
    case (keyGrave, [.command]): return .cycleWindows
    case (keyGrave, [.command, .shift]): return .cycleWindowsBackward
    default: return nil
    }
  }
}

/// Live resize sends the window's size to the remote at most `interval` apart, latest wins: the
/// remote app relays out continuously without a backlog of stale sizes.
public struct FusionResizeThrottle {
  public let interval: TimeInterval
  private var lastSent: TimeInterval = -.infinity
  private(set) public var pending: CGRect?

  public init(interval: TimeInterval = 1.0 / 30) { self.interval = interval }

  /// The frame to send now, or nil when it is kept (replacing any earlier one) for `flush`.
  public mutating func offer(_ frame: CGRect, now: TimeInterval) -> CGRect? {
    if now - lastSent >= interval {
      lastSent = now
      pending = nil
      return frame
    }
    pending = frame
    return nil
  }

  /// The kept frame once its turn has come.
  public mutating func flush(now: TimeInterval) -> CGRect? {
    guard let frame = pending, now - lastSent >= interval else { return nil }
    lastSent = now
    pending = nil
    return frame
  }

  /// When the kept frame may go, for a timer.
  public var nextDeadline: TimeInterval? { pending == nil ? nil : lastSent + interval }

  public mutating func reset() {
    pending = nil
    lastSent = -.infinity
  }
}

/// Which pasteboard changes cross between the Macs. Password managers mark their copies; those,
/// and anything we wrote ourselves (which would bounce back forever), never leave.
public struct FusionClipboardGuard {
  public static let maxBytes = 8 << 20
  public static let concealedTypes: Set<String> = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
    "com.typeit4me.clipping",
    "Pasteboard generator type",
    "net.antelle.keeweb",
  ]

  private var written: Int?
  private var seen: Int?
  /// Nothing crosses until a fused window has had the focus at least once in this session.
  public var armed = false

  public init() {}

  /// Call after writing to the pasteboard ourselves, with its new change count.
  public mutating func didWrite(changeCount: Int) {
    written = changeCount
    seen = changeCount
  }

  /// Whether `changeCount` is worth reading at all.
  public func isUnseen(changeCount: Int) -> Bool { armed && changeCount != seen }

  /// Whether the pasteboard's current contents should be sent to the other Mac.
  public mutating func shouldSend(changeCount: Int, types: [String], bytes: Int) -> Bool {
    guard armed, changeCount != seen else { return false }
    seen = changeCount
    if changeCount == written { return false }
    if types.contains(where: { Self.concealedTypes.contains($0) }) { return false }
    return bytes > 0 && bytes <= Self.maxBytes
  }

  /// Marks the current contents as already known, so arming does not send what was copied before.
  public mutating func observe(changeCount: Int) {
    seen = changeCount
  }
}

/// Clipboard contents as they travel between the Macs: plain text, RTF and PNG only.
public struct FusionClipboardItem: Equatable {
  public var text: String?
  public var rtf: Data?
  public var png: Data?

  public init(text: String? = nil, rtf: Data? = nil, png: Data? = nil) {
    self.text = text; self.rtf = rtf; self.png = png
  }

  public var bytes: Int { (text?.utf8.count ?? 0) + (rtf?.count ?? 0) + (png?.count ?? 0) }
  public var isEmpty: Bool { text == nil && rtf == nil && png == nil }

  public static func read(_ pasteboard: NSPasteboard) -> FusionClipboardItem {
    var item = FusionClipboardItem()
    item.text = pasteboard.string(forType: .string)
    item.rtf = pasteboard.data(forType: .rtf)
    if let png = pasteboard.data(forType: .png) {
      item.png = png
    } else if let tiff = pasteboard.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) {
      item.png = rep.representation(using: .png, properties: [:])
    }
    return item
  }

  /// Writes the item and returns the pasteboard's new change count.
  @discardableResult
  public func write(to pasteboard: NSPasteboard) -> Int {
    pasteboard.clearContents()
    if let text { pasteboard.setString(text, forType: .string) }
    if let rtf { pasteboard.setData(rtf, forType: .rtf) }
    if let png { pasteboard.setData(png, forType: .png) }
    return pasteboard.changeCount
  }

  public var message: [String: Any] {
    var m: [String: Any] = ["t": "clip"]
    if let text { m["text"] = text }
    if let rtf { m["rtf"] = rtf.base64EncodedString() }
    if let png { m["png"] = png.base64EncodedString() }
    return m
  }

  public init?(message m: [String: Any]) {
    self.init(text: m["text"] as? String,
              rtf: (m["rtf"] as? String).flatMap { Data(base64Encoded: $0) },
              png: (m["png"] as? String).flatMap { Data(base64Encoded: $0) })
    guard !isEmpty, bytes <= FusionClipboardGuard.maxBytes else { return nil }
  }
}

/// Remote window levels mapped to this Mac's: a floating palette floats over its app, a menu is
/// a menu. Anything unknown in between is treated as floating rather than as a menu.
public enum FusionWindowLevels {
  public static func local(remoteLayer: Int) -> NSWindow.Level {
    switch remoteLayer {
    case ..<1: return .normal
    case 1..<8: return .floating
    case 8..<20: return .modalPanel
    case 20..<24: return .submenu
    case 24..<101: return .floating
    case 101: return .popUpMenu
    default: return remoteLayer >= Int(CGWindowLevelForKey(.screenSaverWindow)) ? .popUpMenu : .statusBar
    }
  }
}

