// Rasterize the existing mobile SVGs: CoreSVG misreads their compact arc paths.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
const source = readFileSync(new URL("../../client/src/theme/agent-marks.ts", import.meta.url), "utf8");
const marks = JSON.parse(source.slice(source.indexOf("{", source.indexOf("export const"))).trim().replace(/;$/, ""));
const png = {};
for (const [agent, mark] of Object.entries(marks)) {
  for (const theme of ["light", "dark"]) {
    const foreground = mark.fg?.[theme] ?? "#ffffff";
    const size = mark.full ? 96 : 60;
    const offset = (96 - size) / 2;
    const svg = mark.svg.replace(/<path(?![^>]*\bfill=)/g, `<path fill="${foreground}"`).replaceAll("currentColor", foreground)
      .replace("<svg", `<svg x="${offset}" y="${offset}" width="${size}" height="${size}"`);
    const composed = `<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 96 96">${mark.bg?.[theme] ? `<rect width="96" height="96" fill="${mark.bg[theme]}"/>` : ""}${svg}</svg>`;
    png[agent + theme] = (await sharp(Buffer.from(composed)).png().toBuffer()).toString("base64");
  }
}
const output = `// Generated by scripts/generate-agent-marks.mjs from the existing mobile assets.
// Official marks from @lobehub/icons (MIT); do not edit these images by hand.
import Foundation

enum DesktopAgentAssets {
  static let png = (try? JSONDecoder().decode([String: String].self, from: Data(json.utf8))) ?? [:]
  private static let json = #\"\"\"
${JSON.stringify(png)}
\"\"\"#
}
`;
const target = fileURLToPath(new URL("../Sources/LinkShell/DesktopAgentAssets.swift", import.meta.url));
if (!existsSync(target) || readFileSync(target, "utf8") !== output) writeFileSync(target, output);
