/**
 * The few strings the native shell draws itself (menus, tray, dialogs, the loading and error
 * pages, updater progress). They follow the page's language, which it sends as
 * `{ action: "locale" }`; the last one is kept in settings so the menu is right before the page loads.
 */
export type MainLocale = "zh" | "en" | "ja";

export function normalizeMainLocale(value: unknown): MainLocale | undefined {
  return value === "zh" || value === "en" || value === "ja" ? value : undefined;
}

