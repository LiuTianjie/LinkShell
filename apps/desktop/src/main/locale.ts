const DICTIONARIES: Record<MainLocale, Dictionary> = { zh, en, ja };

export function translateMain(locale: MainLocale, key: MainKey, params: Record<string, string | number> = {}): string {
  const template = DICTIONARIES[locale][key] ?? zh[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

/**
 * LinkShellNative's Sparkle bridge words its progress in Chinese; the known messages are
 * re-worded here so the Updates page reads in the page's language. Unknown text passes through.
 */
const SPARKLE_MESSAGES: Array<[RegExp, MainKey]> = [
  [/^更新服务未就绪：(?<message>.*)$/s, "mac.notReady"],
  [/^正在检查 App 更新…$/, "mac.checking"],
  [/^正在确认后台服务停止…$/, "mac.stopping"],
  [/^正在打开更新窗口…$/, "mac.opening"],
  [/^可更新至 LinkShell (?<version>\S+)$/, "mac.available"],
  [/^当前已是此通道的最新版本$/, "mac.current"],
  [/^正在下载 LinkShell (?<version>\S+)（后台服务保持连接）…$/, "mac.downloading"],
  [/^下载完成，点击“Install and Relaunch”即可安装并重启$/, "mac.downloaded"],
  [/^正在安装，LinkShell 将重新打开…$/, "mac.installing"],
];

export function localizeUpdaterMessage(locale: MainLocale, message: unknown): unknown {
  if (typeof message !== "string" || locale === "zh") return message;
  for (const [pattern, key] of SPARKLE_MESSAGES) {
    const match = pattern.exec(message);
    if (match) return translateMain(locale, key, match.groups ?? {});
  }
  return message;
}
